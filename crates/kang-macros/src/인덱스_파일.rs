// `build.rs` 와 매크로가 **같은 규칙으로** 인덱스 파일을 찾고 읽는다.
//
// 둘은 컴파일 단위가 갈려 있어 (한쪽은 build script, 한쪽은 proc-macro 라이브러리)
// 모듈로 나눠 쓸 수 없다. 그래서 `include!` 로 소스를 공유한다. 탐색 규칙이 두 벌이
// 되면 갈리고, 갈리면 **`build.rs` 가 추적하지 않는 인덱스를 매크로가 읽는다** — 그때
// 검증은 한 번 성공한 뒤 영원히 캐시되고, 문서를 고쳐도 낡은 rev 로 통과한다.
//
// `include!` 되는 파일이라 안쪽 문서 주석(`//!`)을 쓸 수 없다. 이 파일을 고칠 때는
// `build.rs` 도 함께 건드려라 — cargo 는 build script 를 `build.rs` 하나로 지문 삼으므로,
// 이 파일만 고치면 build script 바이너리가 다시 컴파일되지 않는다.

use std::io::Read;

/// 인덱스를 찾지 못했을 때 위로 훑는 관례 경로.
const 관례_경로: &str = ".kang/index.tsv";

/// 인덱스로 받아들이는 최대 크기.
///
/// 인덱스 한 줄은 `{종류}\t{rev}\t{주소}` 이고, 이 저장소의 인덱스는 심볼 26 개에
/// 1,232 바이트다 — 줄당 50 바이트 남짓이다. 16 MiB 는 그 기준으로 심볼 33 만 개가
/// 넘는 양이고, 그 규모에 닿기 전에 `kang build` 가 먼저 무너진다.
///
/// **상한을 두는 이유는 크기가 아니라 신뢰다.** `KANG_INDEX` 는 빌드 환경이 주는
/// 값이고, 그것이 가리키는 대상을 rustc 프로세스 메모리에 통째로 올린다.
const 인덱스_최대_바이트: u64 = 16 * 1024 * 1024;

/// 인덱스 경로를 정한다. **매크로와 `build.rs` 의 유일한 탐색 규칙이다.**
///
/// `KANG_INDEX` 가 있으면 그것이고, 없으면 `CARGO_MANIFEST_DIR` 부터 위로 훑어 처음
/// 만나는 `.kang/index.tsv` 다. 워크스페이스 루트에 인덱스를 두는 경우가 뒤쪽 경로다 —
/// 어느 쪽도 워크스페이스 루트를 직접 알지 못하므로 위로 훑는다.
///
/// **두 호출자의 기준점이 다르다.** 매크로는 rustc 안에서 돌므로 소비자 크레이트의
/// manifest 디렉토리를 받고, `build.rs` 는 `kang-macros` 자신의 manifest 디렉토리를
/// 받는다. 그래서 `kang-macros` 가 레지스트리 캐시에서 온 의존성이면 `build.rs` 의
/// 위로 훑기가 소비자의 인덱스에 닿지 못한다 — 그런 프로젝트는 `.cargo/config.toml` 의
/// `[env]` 로 `KANG_INDEX` 를 줘야 추적이 붙는다. 한 저장소 안(이 워크스페이스가 그렇다)
/// 에서는 둘 다 같은 루트로 올라가므로 같은 파일을 가리킨다.
///
/// # 반환값
/// 찾은 인덱스 경로. 어느 쪽으로도 정하지 못하면 `None`
fn 인덱스_경로() -> Option<std::path::PathBuf> {
    // 환경 변수가 있으면 그것이 답이다. 파일이 없어도 관례 경로로 넘어가지 않는다 —
    // 넘어가면 "지정한 곳과 다른 곳을 읽었다" 가 된다.
    if let Some(값) = std::env::var_os("KANG_INDEX") {
        return Some(std::path::PathBuf::from(값));
    }

    // cargo 없이 rustc 를 직접 부르면 이 변수가 없다. 그때는 훑을 기준점이 없다.
    let 기준 = std::env::var_os("CARGO_MANIFEST_DIR")?;

    std::path::Path::new(&기준)
        .ancestors()
        .map(|디렉토리| 디렉토리.join(관례_경로))
        .find(|후보| 후보.is_file())
}

/// 인덱스 파일을 읽는다. **정규 파일이 아니거나 상한을 넘으면 읽지 않는다.**
///
/// `KANG_INDEX` 는 빌드 환경이 주는 값이라 무엇이든 가리킬 수 있다. FIFO 를 가리키면
/// 여는 순간 쓰는 쪽을 기다리며 매달리고, `/dev/zero` 를 가리키면 끝없는 0 을 읽어
/// 메모리를 다 쓴다. 둘 다 rustc 프로세스 안에서 벌어지므로 빌드가 통째로 멈춘다.
///
/// # 매개변수
/// - `경로`: 읽을 인덱스 파일
///
/// # 반환값
/// 파일 내용
///
/// # 오류
/// 읽지 못한 **짧은 사유**. 처방과 위치는 호출자가 붙인다 — 매크로와 `build.rs` 의
/// 진단 형식이 다르기 때문이다
fn 인덱스_읽기(경로: &std::path::Path) -> Result<String, String> {
    let 정보 = 경로.metadata().map_err(|오류| 오류.to_string())?;

    // 정규 파일만 받는다. `metadata` 는 링크를 따라가므로 정규 파일을 가리키는
    // 심볼릭 링크는 통과하고, FIFO·장치 파일·디렉토리는 **열기 전에** 걸린다.
    if !정보.is_file() {
        return Err("정규 파일이 아닙니다 — FIFO·장치 파일·디렉토리는 인덱스가 될 수 없습니다".to_string());
    }

    // 크기를 먼저 본다. 여기서 걸러야 큰 파일을 읽는 비용 자체가 들지 않고,
    // 진단이 실제 크기를 말할 수 있다.
    if 정보.len() > 인덱스_최대_바이트 {
        return Err(너무_큼(정보.len()));
    }

    let 파일 = std::fs::File::open(경로).map_err(|오류| 오류.to_string())?;

    // 크기를 재고 여는 사이에 대상이 바뀔 수 있다. 읽기 자체를 상한으로 묶어
    // 그 틈으로 무한한 입력이 들어오지 못하게 한다. 한 바이트를 더 받는 것은
    // "상한에 딱 맞다" 와 "상한을 넘었다" 를 가르기 위해서다.
    let mut 내용 = String::new();
    파일
        .take(인덱스_최대_바이트 + 1)
        .read_to_string(&mut 내용)
        .map_err(|오류| 오류.to_string())?;
    if 내용.len() as u64 > 인덱스_최대_바이트 {
        return Err(너무_큼(내용.len() as u64));
    }

    Ok(내용)
}

/// 상한을 넘었다는 사유. 두 자리에서 같은 문장을 쓴다.
///
/// # 매개변수
/// - `크기`: 실제 크기(바이트)
///
/// # 반환값
/// 실제 크기와 상한을 담은 한 줄
fn 너무_큼(크기: u64) -> String {
    format!("{크기} 바이트로 상한 {인덱스_최대_바이트} 바이트를 넘습니다")
}

/// 인덱스 한 줄을 `(종류, rev, 주소)` 로 가른다.
///
/// 칸이 셋보다 적은 줄은 버린다 — 빈 줄과 잘린 줄이 조용히 심볼로 읽히지 않게 한다.
/// **가변 길이 필드가 마지막이라** `splitn(3, '\t')` 가 심볼 이름에 든 탭을 살린다
/// (V0004 Task 3).
///
/// # 매개변수
/// - `인덱스`: 인덱스 파일 내용
///
/// # 반환값
/// 줄마다 `(종류, rev, 주소)`
fn 줄들(인덱스: &str) -> impl Iterator<Item = (&str, &str, &str)> {
    인덱스.lines().filter_map(|줄| {
        let mut 칸 = 줄.splitn(3, '\t');
        Some((칸.next()?, 칸.next()?, 칸.next()?))
    })
}
