//! `kang init` — 에이전트 진입점과 스킬 파일을 만든다 (스펙 6.1).
//!
//! kang 의 창립 원칙인 "LLM 은 원본을 보지 않는다" 는 **강제할 수 없다** — 에이전트는
//! `.kang` 파일을 그냥 읽을 수 있다. 저장소에 `.kang` 만 있으면 에이전트는 그게 무엇인지
//! 모르고 `cat` 하고, `cat` 으로 읽은 `.kang` 은 import 간접 참조 때문에 마크다운보다
//! 읽기 나쁘다. 이 모듈이 만드는 스킬 파일이 그 원칙을 성립시키는 유일한 장치다.
//!
//! ponytail: 네 산출물을 [`ensure_section`] 하나로 처리한다. 복사·섹션 덧붙임·한 줄
//! 덧붙임·템플릿 생성은 전부 "marker 가 없을 때만 덧붙인다" 의 변형이다.
//!
//! **이 모듈은 사용자 파일에 쓰지만 [`crate::bless`] 의 원자성을 요구하지 않는다.**
//! 근거는 쓰기의 모양에 있다 — `bless` 는 파일 **안**의 바이트를 치환하므로 도중에 죽으면
//! 반쯤 잘린 문서가 남고 되돌릴 곳이 없지만, 여기는 파일 **끝**에만 append 하므로 최악이
//! "끝에 덜 쓰인 섹션" 이고 기존 바이트는 그대로다. 그 상태에는 marker 가 없으므로 다시
//! 실행하면 이어받는다. 즉 재실행이 복구이며, 임시 파일과 rename 이 더 줄일 위험이 없다.
//!
//! 대신 `bless` 가 지지 않는 짐이 하나 있다. **덧붙일 대상이 사용자의 산문 파일이므로
//! marker 판정이 유일한 방어선이다** — 판정이 어긋나면 두 번 붙거나 영구히 붙지 않는다.
//! 그 판정의 근거는 [`ensure_section`] 에 있다.

use crate::resolve;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Claude 스킬의 내용. **컴파일 타임에 바이너리에 임베드한다** — 릴리즈된 바이너리는
/// 저장소 파일에 접근할 수 없으므로 런타임에 찾을 곳이 없다.
const 스킬: &str = include_str!("skill.md");

/// 스킬 파일의 루트 기준 경로. **스킬 내용의 유일한 사본**이며 나머지 둘이 이것을 가리킨다.
const 스킬_경로: &str = ".claude/skills/kang/SKILL.md";

/// Codex 용 진입점. 내용을 복제하지 않고 스킬을 가리키기만 한다 — 두 파일에 복제하면
/// kang 이 막으려는 SoT 분열이 kang 자신의 도구에서 일어난다.
const AGENTS_섹션: &str = "## kang

이 프로젝트의 문서는 kang 으로 유지보수된다. 문서를 읽거나 쓰기 전에
`.claude/skills/kang/SKILL.md` 를 읽어라. 사용법의 사본은 그 파일 하나뿐이다.
";

/// Claude 용 한 줄 진입점 (스펙 6.1). 스킬을 가리키기만 한다.
const CLAUDE_줄: &str = "이 프로젝트의 문서는 kang 으로 유지보수된다. `.claude/skills/kang/SKILL.md` 의 kang 스킬을 사용하여야 한다.
";

/// [`CLAUDE_줄`] 의 멱등 판정 접두사.
///
/// 줄 전체를 marker 로 삼지 않는다 — 사람이 그 줄에 자기 말을 덧붙이는 것이 이 파일에서
/// 가장 흔한 편집이고, 그때 안내가 두 번 붙으면 안 된다.
const CLAUDE_MARKER: &str = "이 프로젝트의 문서는 kang 으로 유지보수된다";

/// 첫 문서 템플릿. **그 자체로 합법 kang 문서여야 한다** — `init` 직후의 `kang build` 가
/// 실패하면 사용자의 첫 경험이 "도구가 만든 파일이 도구를 통과하지 못한다" 다.
///
/// 그래서 본문의 백틱은 이 문서가 선언한 keyword 하나뿐이고(스펙 4.2), 안내문은 전부
/// topic 안에 있고(스펙 3절), import 가 없으므로 rev 핀도 필요하지 않다(스펙 4.8).
const 예제_문서: &str = "---
description: kang 이 만든 첫 문서. 이 프로젝트의 실제 정책으로 바꾸세요.
---

keyword `예시 개념`: 이 프로젝트를 아는 사람에게 즉시 특정 개념을 떠올리게 하는 용어

## 예시 개념을 쓰는 방법

이 문서의 모든 백틱은 심볼 참조입니다. `예시 개념` 처럼 선언된 이름만 쓸 수 있고,
선언되지 않은 이름을 백틱으로 감싸면 컴파일 error 가 납니다.

topic 밖에는 내용을 둘 수 없습니다. 문서 제목도 서문도 두지 않습니다 — 제목은 파일
경로가, 서문은 frontmatter 의 description 이 담당합니다.

다른 문서의 개념은 최상단의 import 선언으로 당겨 씁니다. 나머지 사용법은
.claude/skills/kang/SKILL.md 에 있습니다.
";

/// 현재 프로젝트에 에이전트 진입점을 만든다.
///
/// **기존 파일은 덮어쓰지 않는다.** 세 마크다운 진입점에는 kang 섹션이 없을 때만 그것을
/// 덧붙이고, 첫 `.kang` 문서는 프로젝트에 문서가 없고 그 경로가 비어 있을 때만 만든다 —
/// 스펙 6.1 이 앞의 셋에만 "섹션만 덧붙인다" 를 배정하고 `.kang` 은 "템플릿" 으로 가른다.
///
/// **산출물마다의 처리 결과를 이 함수가 직접 표준 오류로 찍는다.** 부르는 쪽이 모아 찍게
/// 하면 중간에 실패했을 때 그때까지 만든 것을 말할 방법이 사라진다 — `init` 은 `bless`
/// 와 달리 여러 파일을 쓰므로 부분 적용이 정상 상태이고, 흐르며 찍으면 실패 지점 앞의
/// 보고가 이미 나가 있다. 만든 것과 건너뛴 것을 구분해 말한다.
///
/// # 매개변수
/// - `root`: 파일을 만들 프로젝트 루트. git 저장소가 아니어도 되며, 그때는 부르는 쪽이
///   현재 디렉토리를 넘긴다 (스펙 6.1)
///
/// # 반환값
/// 이번 실행이 **만든** 파일들의 절대 경로. 전부 건너뛰었으면 빈 목록
///
/// # 오류
/// 산출물 하나라도 쓰지 못하면 그 사정. 그 앞의 산출물은 이미 만들어졌고 이미 보고됐으며,
/// 다시 실행하면 만들어진 것을 건너뛴다
pub fn init(root: &Path) -> Result<Vec<PathBuf>, String> {
    // marker 는 전부 그 내용 안의 한 줄이다. 어긋나면 두 번 실행할 때 두 번 붙는다.
    let mut 산출물: Vec<(&str, &str, &str)> = vec![
        // 스킬 파일의 frontmatter `name` 을 marker 로 삼는다. Claude 가 스킬을 찾는 키이므로
        // 사람이 본문을 고쳐도 남아 있고, 첫 줄인 `---` 은 어느 마크다운에나 있어 못 쓴다.
        (스킬_경로, "name: kang", 스킬),
        ("AGENTS.md", "## kang", AGENTS_섹션),
        ("CLAUDE.md", CLAUDE_MARKER, CLAUDE_줄),
    ];

    // 이미 kang 을 쓰는 프로젝트에 예제 템플릿을 더하면 쓰레기가 생긴다 (스펙 6.1).
    // 판정은 파일 하나의 유무가 아니라 **프로젝트에 문서가 있는지**다.
    //
    // **그 위에 `exists()` 를 더한다.** [`resolve::load`] 는 파싱에 성공한 문서만 돌려주므로
    // 그것만 보면 **파싱에 실패하는 초안만 있는 프로젝트가 "문서가 없다" 로 읽힌다.** 그때
    // [`ensure_section`] 은 marker 가 없는 그 초안 끝에 템플릿을 덧붙이고 "만들었습니다"
    // 라고 말한다 — 스펙 6.1 은 "섹션만 덧붙인다" 를 세 마크다운 진입점에만 배정하고 첫
    // `.kang` 은 "템플릿" 으로 구분한다. 사용자 문서에 남의 frontmatter 를 박는 것은
    // 되돌릴 수 없으므로, 그 한 경우를 막는 데 조건 하나가 `create_new` 보다 짧다.
    //
    // ponytail: `.kang` 을 찾는 재귀 순회가 이미 [`resolve::load`] 에 있으므로 그것을
    // 그대로 쓴다. 파싱까지 하는 것은 필요한 일보다 많지만, 순회를 두 번 적으면 두 곳이
    // 갈라진다. 순회 비용이 문제가 되면 `수집` 을 공개한다.
    let 예제 = "docs/example.kang";
    let 예제_필요 = resolve::load(root).0.docs.is_empty() && !root.join(예제).exists();
    if 예제_필요 {
        산출물.push((예제, "description:", 예제_문서));
    }

    let mut 만든것: Vec<PathBuf> = Vec::new();
    // 산출물을 차례로 처리한다. 하나가 실패하면 그 앞은 이미 만들어진 채로 남는다.
    for (상대, marker, 내용) in 산출물 {
        let path = root.join(상대);
        match ensure_section(&path, marker, 내용)? {
            // 만든 것을 이름으로 말한다. "만들었습니다" 만으로는 사용자가 확인할 수 없다.
            true => {
                eprintln!("만들었습니다: {상대}");
                만든것.push(path);
            }
            // 건너뛴 것을 만들었다고 하면 검증하면 거짓이다.
            false => eprintln!("이미 kang 안내가 있어 건너뜁니다: {상대}"),
        }
    }

    // 만들지 않은 것도 말한다. 침묵하면 사용자는 예제가 생겼다고 믿는다.
    if !예제_필요 {
        eprintln!("이미 .kang 문서가 있어 건너뜁니다: {예제}");
    }

    Ok(만든것)
}

/// 파일이 없으면 만들고, 있으면 marker 로 시작하는 섹션이 없을 때만 덧붙인다.
/// 네 산출물이 전부 이 한 함수로 처리된다 — 복사·섹션 덧붙임·한 줄 덧붙임·
/// 템플릿 생성은 전부 같은 규칙의 변형이다.
///
/// **멱등 판정은 줄 단위 접두 일치다.** 문자열 포함으로 보면 marker 를 산문 안에 인용한
/// 파일이 이미 안내를 가진 것으로 오판되어 안내가 영구히 붙지 않는다 — 인용은 지시가
/// 아니다. 반대로 줄 전체 일치로 보면 사람이 제목에 낱말을 덧붙인 순간 두 번 붙는다.
///
/// ponytail: 접두 일치이므로 `## kang` 은 `## kangaroo` 에도 걸린다. marker 는 kang 이
/// 고른 문자열이고 그런 제목을 가진 파일은 실측된 적이 없다. 문제가 되면 marker 뒤에
/// 줄 끝이나 공백을 요구한다.
///
/// **덮어쓰지 않고 이어 쓴다.** `write` 는 먼저 파일을 비우므로 도중에 죽으면 사용자의
/// `CLAUDE.md` 가 사라진다. append 모드는 기존 바이트를 건드리지 않으므로 최악의 경우가
/// "끝에 덜 쓰인 섹션이 붙는다" 이고, 그 상태는 marker 가 없으니 다시 실행하면 붙는다.
///
/// # 매개변수
/// - `path`: 쓸 파일의 절대 경로. 중간 디렉토리는 만든다
/// - `marker`: 이미 처리됐음을 뜻하는 줄 접두사. `내용` 안의 한 줄이어야 한다
/// - `내용`: 덧붙일 텍스트. 개행으로 끝나야 한다
///
/// # 반환값
/// 덧붙였으면 `true`, marker 가 이미 있어 건너뛰었으면 `false`
///
/// # 오류
/// 파일을 읽지 못하거나 디렉토리를 만들지 못하거나 쓰지 못하면 그 사정
fn ensure_section(path: &Path, marker: &str, 내용: &str) -> Result<bool, String> {
    // 없는 파일은 빈 파일과 같게 다룬다 — 만드는 경우와 덧붙이는 경우가 한 갈래가 된다.
    let 기존 = match std::fs::read_to_string(path) {
        Ok(기존) => 기존,
        Err(오류) if 오류.kind() == std::io::ErrorKind::NotFound => String::new(),
        // 권한이 없거나, UTF-8 이 아니거나, 중간 경로가 파일이라 디렉토리로 들어갈 수
        // 없는 경우(`ENOTDIR`). 삼키면 남의 파일을 못 읽은 채 덧붙인다.
        Err(오류) => return Err(format!("{} 를 읽지 못했습니다 — {오류}", path.display())),
    };

    // 이미 안내가 있으면 아무것도 하지 않는다.
    if 기존.lines().any(|줄| 줄.starts_with(marker)) {
        return Ok(false);
    }

    // 스킬 파일은 세 단계 깊이다. 상위 디렉토리에 쓸 권한이 없으면 여기서 실패하고,
    // 그것은 문서가 틀린 것이 아니므로 환경 오류다.
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|오류| format!("{} 를 만들지 못했습니다 — {오류}", parent.display()))?;
    }

    // 기존 파일이 개행으로 끝나지 않으면 섹션이 그 마지막 줄에 달라붙는다. 빈 줄 하나를
    // 사이에 두는 것은 마크다운에서 섹션 경계이기도 하다.
    let 앞 = match (기존.is_empty(), 기존.ends_with('\n')) {
        (true, _) => "",
        (false, true) => "\n",
        (false, false) => "\n\n",
    };

    let mut 파일 = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)
        .map_err(|오류| format!("{} 를 열지 못했습니다 — {오류}", path.display()))?;
    파일
        .write_all(format!("{앞}{내용}").as_bytes())
        .map_err(|오류| format!("{} 에 쓰지 못했습니다 — {오류}", path.display()))?;

    Ok(true)
}
