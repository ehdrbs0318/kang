import { kangTopic } from "../.kang/generated";

/** 한 번의 결제가 덮는 기간(일). 이 예시는 월 구독 하나만 판다. */
const 구독기간 = 30;

/** 환불 요청에 대한 판정. `승인` 이 거짓이면 `금액` 은 0 이다. */
export type 환불판정 = { 승인: boolean; 금액: number };

/**
 * 환불 요청을 정책대로 판정한다.
 *
 * 각 메소드의 `@kangTopic` 이 그 메소드가 구현하는 정책의 주소와, 구현할 때 읽은
 * 원문의 rev 핀을 담는다. 정책 원문이 바뀌면 핀이 어긋나 `tsc` 가 컴파일을 세운다.
 */
export class 환불서비스 {
  /**
   * 접수된 환불 요청을 받아 줄지 판정한다.
   *
   * @param 경과일 - 결제일로부터 접수일까지 지난 날 수
   * @param 결제금액 - 원래 결제된 금액
   * @param 사용일 - 구매자가 이미 사용한 날 수
   * @returns 승인 여부와 돌려줄 금액
   */
  @kangTopic("docs/refunds#환불 가능 기간", "cdd44d")
  판정한다(경과일: number, 결제금액: number, 사용일: number): 환불판정 {
    // 정책이 정한 기간은 30일이고 31일째부터는 거절한다. 정산 여부는 묻지 않는다 —
    // 판매자에게서 회수하는 절차가 구매자를 기다리게 하지 않는다는 것이 정책이다.
    if (경과일 > 30) {
      return { 승인: false, 금액: 0 };
    }

    return { 승인: true, 금액: this.돌려줄금액(결제금액, 사용일) };
  }

  /**
   * 사용하지 않은 기간에 해당하는 금액만 계산한다.
   *
   * @param 결제금액 - 원래 결제된 금액
   * @param 사용일 - 이미 사용한 날 수. 하루라도 쓴 날은 온전히 센다
   * @returns 돌려줄 금액. 전 기간을 다 썼으면 0
   */
  @kangTopic("docs/proration#부분 환불의 계산", "970bc8")
  돌려줄금액(결제금액: number, 사용일: number): number {
    // 하루 단위로 자르고, 하루라도 쓴 날은 온전히 센다. 결제 당일(사용일 0)도
    // 하루를 쓴 것으로 세라는 것이 정책이므로 최소 1 이다.
    const 사용한일 = Math.max(1, Math.ceil(사용일));

    return Math.floor((결제금액 * Math.max(0, 구독기간 - 사용한일)) / 구독기간);
  }
}
